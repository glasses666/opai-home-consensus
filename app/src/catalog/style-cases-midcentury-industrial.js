const list = (...items) => Object.freeze(items);
const source = (url, kind) => Object.freeze({ url, kind, usage: 'reference_only' });
const budget = (band) => Object.freeze({ band, provenance: 'curated_estimate' });
const evidence = (sourceFacts, curatedInferences, unknowns) => Object.freeze({
  sourceFacts: list(...sourceFacts),
  curatedInferences: list(...curatedInferences),
  unknowns: list(...unknowns),
});

function normalizeCase(item) {
  return Object.freeze({
    id: item.id,
    styleId: item.styleId,
    title: item.title,
    url: item.url,
    sourceKind: item.sourceKind,
    source: source(item.url, item.sourceKind),
    geography: item.geography,
    climate: item.climate,
    dwellingType: item.dwellingType,
    rooms: list(...item.rooms),
    household: item.household,
    constraints: list(...item.constraints),
    designMoves: list(...item.designMoves),
    envelope: list(...item.envelope),
    furniture: list(...item.furniture),
    lighting: list(...item.lighting),
    intensity: item.intensity,
    budgetBand: item.budgetBand,
    budget: budget(item.budgetBand),
    applicability: list(...item.applicability),
    risks: list(...item.risks),
    evidence: evidence(item.evidence.sourceFacts, item.evidence.curatedInferences, item.evidence.unknowns),
  });
}

